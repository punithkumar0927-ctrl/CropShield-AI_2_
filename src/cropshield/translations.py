def translate(key: str, language: str = "en") -> str:
    """Return a locally translated UI string, falling back to English."""
    selected = language if language in LANGUAGES else "en"
    return TRANSLATIONS.get(selected, TRANSLATIONS["en"]).get(key, TRANSLATIONS["en"].get(key, key))
